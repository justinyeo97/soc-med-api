-- A user can attach at most one run to a post; runs can also exist on their own.
CREATE TABLE public.runs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  post_id bigint UNIQUE REFERENCES public.posts(id) ON DELETE SET NULL,
  title text,
  started_at timestamptz NOT NULL,
  distance_m integer NOT NULL CHECK (distance_m > 0),
  elapsed_seconds integer NOT NULL CHECK (elapsed_seconds > 0),
  moving_seconds integer CHECK (
    moving_seconds >= 0 AND moving_seconds <= elapsed_seconds
  ),
  elevation_gain_m numeric(8, 2) CHECK (elevation_gain_m >= 0),
  average_heart_rate smallint CHECK (average_heart_rate BETWEEN 1 AND 250),
  max_heart_rate smallint CHECK (max_heart_rate BETWEEN 1 AND 250),
  source text NOT NULL DEFAULT 'manual',
  external_id text,
  visibility text NOT NULL DEFAULT 'private'
    CHECK (visibility IN ('public', 'friends', 'private')),
  route_path text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (average_heart_rate IS NULL OR max_heart_rate IS NULL OR max_heart_rate >= average_heart_rate)
);

CREATE UNIQUE INDEX runs_source_external_id_key
  ON public.runs (user_id, source, external_id)
  WHERE external_id IS NOT NULL;

CREATE INDEX runs_user_started_at_idx
  ON public.runs (user_id, started_at DESC, id DESC);

CREATE INDEX runs_public_leaderboard_idx
  ON public.runs (started_at DESC, distance_m DESC)
  WHERE visibility = 'public';

ALTER TABLE public.runs ENABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT, UPDATE, DELETE ON public.runs TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.runs_id_seq TO authenticated;

CREATE POLICY "Users can read runs allowed by visibility"
ON public.runs FOR SELECT TO authenticated
USING (
  visibility = 'public'
  OR user_id = (SELECT auth.uid())
  OR (
    visibility = 'friends'
    AND EXISTS (
      SELECT 1 FROM public.friendships f
      WHERE f.follower_id = (SELECT auth.uid()) AND f.followed_id = runs.user_id
    )
    AND EXISTS (
      SELECT 1 FROM public.friendships f
      WHERE f.follower_id = runs.user_id AND f.followed_id = (SELECT auth.uid())
    )
  )
);

CREATE POLICY "Users can create their own runs"
ON public.runs FOR INSERT TO authenticated
WITH CHECK (
  user_id = (SELECT auth.uid())
  AND (
    post_id IS NULL
    OR EXISTS (
      SELECT 1 FROM public.posts p
      WHERE p.id = runs.post_id AND p.author_id = (SELECT auth.uid())
    )
  )
);

CREATE POLICY "Users can update their own runs"
ON public.runs FOR UPDATE TO authenticated
USING (user_id = (SELECT auth.uid()))
WITH CHECK (
  user_id = (SELECT auth.uid())
  AND (
    post_id IS NULL
    OR EXISTS (
      SELECT 1 FROM public.posts p
      WHERE p.id = runs.post_id AND p.author_id = (SELECT auth.uid())
    )
  )
);

CREATE POLICY "Users can delete their own runs"
ON public.runs FOR DELETE TO authenticated
USING (user_id = (SELECT auth.uid()));
